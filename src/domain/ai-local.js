/**
 * 生成一条答复（纯文本）。
 * @param {object|null} pet 注入的宠物档案（null = 通用模式）
 * @param {string} question 用户问句
 * @param {string} sceneId 场景 id
 * @returns {string}
 */
export function localAnswer(pet, question, sceneId) {
  const p = pet;
  const pn = p ? p.name : '宠物';
  const br = p ? p.breed : '';
  const age = p ? petAgeOf(p) : '';
  const w = p ? p.weight : '';
  const size = p ? sizeSummaryOf(p) : '';
  const q = String(question || '');

  if (sceneId === 'ask') {
    const hit = SYMPTOM_ANSWERS.find((s) => q.indexOf(s[0]) >= 0);
    if (hit) {
      return hit[1] + (size ? '\n【档案联动】当前体型：' + size : '');
    }
    return '【可能原因】结合' + pn + '的情况（' + br + '，' + age + '），常见原因包括：进食过快、环境应激、轻微肠胃不适。\n' +
      '【居家观察】1.禁食4-6小时观察精神状态；2.少量多次提供温水；3.记录发生频率与伴随表现。\n' +
      '【就医信号】出现持续症状、精神萎靡、拒食超过24小时，请尽快就医。\n' +
      '【提醒】以上为科普级参考，不能替代兽医面诊。';
  }

  if (sceneId === 'care') {
    return '结合' + pn + '的当前档案数据（体重' + w + 'kg' + (size ? '，' + size : '') + '），这个情况通常与日常习惯有关。\n' +
      '建议：1）保持规律作息，减少环境应激；2）饮食维持七日不变，观察食欲与排便；3）每日在健康页打卡记录。\n' +
      '若出现连续异常，我会自动生成归因分析报告，首页健康概览也会标红提醒。';
  }

  if (sceneId === 'feed') {
    if (!p || !w) return '请先在档案中完善宠物体重信息，可获得精准计算。';
    const kcalPerKg = p.species === '猫' ? 60 : 50;
    const kcal = Math.round(w * kcalPerKg);
    return '根据档案计算：\n' +
      '【基础热量】' + pn + '体重 ' + w + 'kg × ' + (p.species === '猫' ? '60 kcal/kg（成猫系数）' : '45-55 kcal/kg（按体型取 50）') + ' ≈ ' + kcal + ' kcal/天\n' +
      '【换算克数】以主粮约3.5kcal/g计算 ≈ ' + Math.round(kcal / 3.5) + 'g/天，分 2-3 餐\n' +
      '【个性化调整】已考虑绝育状态：' + (p.neuter || '未知') + '，若活动量小可下调10%\n' +
      '【过敏提示】档案标注：' + (p.note || '无已知过敏') + '，选粮请避开相关成分。';
  }

  if (sceneId === 'watch') {
    return '【行为】画面中' + pn + '刚从猫爬架跳下，正在窗台附近缓慢踱步巡逻。\n' +
      '【情绪】尾巴自然下垂摆动，耳朵朝前，整体情绪平稳偏好奇。\n' +
      '【异常】未发现踱步异常或应激表现。当前时段活动量与近7日均值接近。\n' +
      '建议保持监控，我会在异动时推送提醒。';
  }

  if (sceneId === 'attr') {
    return '【异常项】近7日体重曲线整体上行，' + pn + '当前 ' + w + 'kg。\n' +
      '【可能归因】1.近期换粮热量偏高（档案显示10-10新增冻干零食）；2.绝育后代谢下降（档案：' + (p ? p.neuter : '未知') + '）；3.运动量偏少（活力值58）。\n' +
      '【建议】将零食控制在15g/日以内，恢复每日15分钟逗猫互动；若4周内继续上升超过10%，建议体检排查。\n' +
      '【联动】家园虚拟形象已同步「微胖」状态提示。';
  }

  if (sceneId === 'shop') {
    return '结合' + pn + '档案的推荐：\n' +
      '1.【主粮】室内成猫粮 K36 —— 适合室内活动量，含膳食纤维排毛球，适配当前体重 ' + w + 'kg 的每日热量\n' +
      '2.【饮水】智能饮水机 —— 档案显示饮水打卡正常，升级循环过滤可继续巩固\n' +
      '3.【互动】逗猫棒套装 —— 档案活力值58偏低，建议每日互动15分钟提升活力\n' +
      '【安全提示】已自动排除含牛肉成分商品（档案过敏史：' + (p && p.note ? p.note : '无') + '）。\n' +
      '以上为AI推荐，仅供参考。点商品详情页可直接加购。';
  }

  if (sceneId === 'write') {
    return '已为您生成草稿：\n' +
      '【标题备选】\n1.《' + pn + '的一百种撒娇方式》\n2.《谁家的猫这么黏人？哦，是我的》\n3.《凌晨五点，我被' + pn + '踩醒的第N天》\n' +
      '【正文草稿】\n养' + br + '的日常就是：下班进门一秒被扑倒，写稿时键盘上长猫，睡觉时胸口压着一只' + w + 'kg的「暖宝宝」。它不会说话，但我知道，它把我当成了全世界。\n' +
      '（生成内容需编辑确认后发布）';
  }

  if (sceneId === 'trip') {
    return '【行程规划】周末两日携宠 ' + pn + ' 大理行：\n' +
      'D1 上午：驱车/高铁抵达，入住「宠物友好民宿」（档案提示：需提前报备体重' + w + 'kg）\n' +
      'D1 下午：洱海生态廊道慢行（牵绳），傍晚草地撒欢\n' +
      'D2 上午：宠物友好咖啡店打卡，返程\n' +
      '【携宠清单】便携水碗、常用药（续档案过敏提示）、疫苗本（档案显示猫三联在有效期内）、应急联系卡\n' +
      '【提示】大理紫外线强，注意毛发防晒与补水。需要我导出清单到收藏吗？';
  }

  if (sceneId === 'doll') {
    return '【定制建议】为' + pn + '定制3D玩偶：\n' +
      '【尺寸】档案体重' + w + 'kg，建议 15cm 等比缩小款，还原度最佳\n' +
      '【材质】短毛水晶绒（还原' + br + '毛色纹理）\n' +
      '【配饰】推荐搭配迷你项圈与同款橘色围兜，与档案照片一致度更高\n' +
      '【定稿提示】定稿后模型与配饰不可修改，请仔细确认360°预览效果。\n' +
      '可在「定制专区」直接下单，订单将标记「定制」徽标。';
  }

  return '我可以帮你分析症状、算喂食量、解读监控、推荐商品、写帖子。换个说法再问一次试试？';
}

/** 场景开场白（进会话时 AI 的第一句） */
export function localGreeting(sceneId, pet) {
  const pn = pet ? pet.name : '毛孩子';
  const map = {
    ask: '你好，我是' + pn + '的 AI 宠物助手。描述一下症状，我会帮你分析可能原因和就医信号。',
    care: '日常养护随时问我：喂养、洗护、行为习惯都可以。',
    feed: '告诉我档案里的体重，我帮你算每天该喂多少。',
    watch: '我可以帮你解读监控画面里的行为与情绪。',
    attr: '体重、饮食、运动有异常？发我最近的记录，我帮你归因。',
    shop: '说说你家宠物的需求，我按档案（含过敏史）推荐。',
    write: '想发社区帖子？我帮你写标题和正文。',
    trip: '计划带宠出行？我帮你排行程和随身清单。',
    doll: '想定制玩偶？我帮你选尺寸、材质和配饰。',
  };
  return map[sceneId] || map.ask;
}

/** 拒答模板（命中药品剂量类问题） */
export function localRefusal(pet) {
  return '抱歉，涉及药品剂量的问题无法直接回答。药物使用剂量必须遵兽医处方，' +
    (pet ? '请携带' + pet.name + '的档案记录线下就医。' : '请线下就医。');
}
